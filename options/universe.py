def _normalize_ticker(symbol: str) -> str:
    return str(symbol or "").strip().upper().replace(".", "-")


def _load_sp500_from_wikipedia(limit: int) -> list[str]:
    import pandas as pd

    tables = pd.read_html(
        "https://en.wikipedia.org/wiki/List_of_S%26P_500_companies",
        flavor="html5lib",
    )
    symbols = [_normalize_ticker(item) for item in tables[0]["Symbol"].tolist()]
    deduped: list[str] = []
    seen: set[str] = set()
    for symbol in symbols:
        if not symbol or symbol in seen:
            continue
        seen.add(symbol)
        deduped.append(symbol)
    return deduped[:limit]


@lru_cache(maxsize=4)
def get_sp500_tickers(limit: int = 200) -> tuple[str, ...]:
    """Return up to ``limit`` S&P 500 tickers (yfinance spelling)."""
    capped = max(1, min(int(limit), 503))
    try:
        tickers = _load_sp500_from_wikipedia(capped)
        if len(tickers) >= min(capped, 100):
            _SP500_CACHE_PATH.parent.mkdir(parents=True, exist_ok=True)
            _SP500_CACHE_PATH.write_text(
                json.dumps({"tickers": tickers}, indent=2),
                encoding="utf-8",
            )
            return tuple(tickers)
    except Exception:
        pass

    if _SP500_CACHE_PATH.exists():
        try:
            cached = json.loads(_SP500_CACHE_PATH.read_text(encoding="utf-8"))
            tickers = [_normalize_ticker(item) for item in cached.get("tickers") or []]
            if tickers:
                return tuple(tickers[:capped])
        except Exception:
            pass

    merged: list[str] = []
    seen: set[str] = set()
    for symbol in list(SP500_TOP_100_TICKERS) + list(_SP500_FALLBACK_EXTRA):
        normalized = _normalize_ticker(symbol)
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        merged.append(normalized)
    return tuple(merged[:capped])


SP500_TOP_200_TICKERS: tuple[str, ...] = get_sp500_tickers(200)

# Focus universe for per-ticker playbook / registry (liquid mega + sector leaders).
SP500_TOP_40_TICKERS: tuple[str, ...] = SP500_TOP_100_TICKERS[:40]


def get_sp500_top40() -> tuple[str, ...]:
    """Return the fixed top-40 playbook universe."""
    return SP500_TOP_40_TICKERS

